use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

use genco::prelude::*;

use crate::{Inventory, LegacySymbol, LegacyTest, RustTest};

pub fn write_inventory(
    out_dir: &Path,
    inventory: &Inventory,
) -> Result<(), Box<dyn std::error::Error>> {
    fs::create_dir_all(out_dir)?;
    fs::write(
        out_dir.join("inventory.json"),
        serde_json::to_string_pretty(inventory)?,
    )?;
    fs::write(out_dir.join("legacy_tests.rs"), render_tests(&inventory.tests)?)?;
    fs::write(
        out_dir.join("legacy_symbols.rs"),
        render_symbols(&inventory.symbols)?,
    )?;
    fs::write(
        out_dir.join("kani-pairing.md"),
        render_pairing_report(&inventory.tests, &inventory.rust_tests),
    )?;
    Ok(())
}

pub fn write_kani_harnesses(
    root: &Path,
    out_dir: &Path,
    tests: &[RustTest],
) -> Result<(), Box<dyn std::error::Error>> {
    let mut by_crate: BTreeMap<&str, Vec<&RustTest>> = BTreeMap::new();
    for test in tests {
        by_crate.entry(&test.crate_name).or_default().push(test);
    }

    let audit_dir = out_dir.join("kani");
    fs::create_dir_all(&audit_dir)?;

    for (crate_name, crate_tests) in by_crate {
        let rendered = render_kani_target(&crate_tests)?;
        let crate_target = root
            .join("crates")
            .join(crate_name)
            .join("tests")
            .join("blue_kani_generated.rs");
        fs::write(&crate_target, &rendered)?;
        fs::write(audit_dir.join(format!("{crate_name}.rs")), rendered)?;
    }
    Ok(())
}

fn render_symbols(symbols: &[LegacySymbol]) -> Result<String, genco::fmt::Error> {
    let mut rows = rust::Tokens::new();
    for symbol in symbols {
        let source = &symbol.source;
        let qualified_name = &symbol.qualified_name;
        let kind = &symbol.kind;
        quote_in! { rows =>
            ($(quoted(source)), $(quoted(qualified_name)), $(quoted(kind))),
        }
    }

    let tokens: rust::Tokens = quote! {
        // @generated by blue-codegen from Doxygen XML. Do not edit by hand.
        pub const LEGACY_BLUE_SYMBOLS: &[(&str, &str, &str)] = &[
            $rows
        ];
    };
    tokens.to_file_string()
}

fn render_tests(tests: &[LegacyTest]) -> Result<String, genco::fmt::Error> {
    let register = rust::import("blueexposure", "BlueLegacyTestInfo");
    let registry = rust::import("blueexposure", "BlueRegistry");
    let mut body = rust::Tokens::new();

    for test in tests {
        let source = &test.source;
        let legacy = &test.legacy_name;
        let rust_test = match &test.rust_test {
            Some(name) => quote! { Some($(quoted(name)).to_owned()) },
            None => quote! { None },
        };
        quote_in! { body =>
            registry.register_legacy_test($register {
                source: $(quoted(source)).to_owned(),
                legacy_name: $(quoted(legacy)).to_owned(),
                rust_test: $rust_test,
            });
        }
    }

    let tokens: rust::Tokens = quote! {
        // @generated by blue-codegen. Do not edit by hand.
        pub fn register_generated_legacy_tests(registry: &mut $registry) {
            $body
        }
    };
    tokens.to_file_string()
}

fn render_kani_target(tests: &[&RustTest]) -> Result<String, genco::fmt::Error> {
    let mut tokens = rust::Tokens::new();
    quote_in! { tokens =>
        // @generated by blue-codegen + Genco. Do not edit by hand.
        #![cfg(kani)]
        #![allow(dead_code)]
    }

    let mut modules = BTreeMap::<String, String>::new();
    for test in tests {
        modules.entry(test.source.clone()).or_insert_with(|| {
            format!("__blue_source_{}", sanitize_ident(&test.source))
        });
    }

    for (source, alias) in &modules {
        quote_in! { tokens =>
            #[path = $(quoted(source))]
            mod $(alias);
        }
    }

    for test in tests {
        let alias = modules
            .get(&test.source)
            .expect("source module was registered before harness generation");
        let harness = format!("blue_kani_{}", sanitize_ident(&test.semantic_name));
        let mut call_path = alias.clone();
        for nested in test.module_path.iter().skip(1) {
            call_path.push_str("::");
            call_path.push_str(nested);
        }
        call_path.push_str("::");
        call_path.push_str(&test.body_name);

        quote_in! { tokens =>
            #[kani::proof]
            fn $(harness)() {
                $(call_path)();
            }
        }
    }

    tokens.to_file_string()
}

fn render_pairing_report(legacy: &[LegacyTest], rust_tests: &[RustTest]) -> String {
    let mapped = legacy.iter().filter(|test| test.rust_test.is_some()).count();
    let rust_names = rust_tests
        .iter()
        .map(|test| test.semantic_name.clone())
        .collect::<BTreeSet<_>>();
    let dangling = legacy
        .iter()
        .filter_map(|test| test.rust_test.as_deref())
        .filter(|name| !rust_names.contains(*name))
        .count();

    let mut out = format!(
        "# Generated legacy-test / Kani pairing report\n\nLegacy tests mapped to Rust semantics: {mapped}/{}\n\nNative `#[blue_test]` tests with generated Kani harnesses: {}/{}\n\nDangling legacy mappings: {dangling}\n\n",
        legacy.len(),
        rust_tests.len(),
        rust_tests.len(),
    );
    out.push_str(
        "`#[blue_test]` owns the single semantic body and the ordinary `#[test]` wrapper. `blue-codegen` discovers every `#[blue_test]` and Genco emits the `#[kani::proof]` wrappers into each crate's generated Kani integration-test target. Unmapped legacy tests remain migration gaps; the generator never creates placeholder proofs.\n\n",
    );
    out.push_str("## Native Rust / Kani pairs\n\n| Rust semantic test | Generated Kani harness |\n|---|---|\n");
    for test in rust_tests {
        out.push_str(&format!(
            "| `{}` | `blue_kani_{}` |\n",
            test.semantic_name,
            sanitize_ident(&test.semantic_name)
        ));
    }

    out.push_str("\n## Legacy semantic mappings\n\n| Legacy test | Rust semantic test | Kani status |\n|---|---|---|\n");
    for test in legacy {
        let (rust_test, kani) = match &test.rust_test {
            Some(rust_test) if rust_names.contains(rust_test) => {
                (rust_test.as_str(), "generated")
            }
            Some(rust_test) => (rust_test.as_str(), "mapping target not discovered"),
            None => ("—", "—"),
        };
        out.push_str(&format!(
            "| `{}` | `{}` | {} |\n",
            test.legacy_name, rust_test, kani
        ));
    }
    out
}

fn sanitize_ident(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    if out.is_empty() || out.as_bytes()[0].is_ascii_digit() {
        out.insert(0, '_');
    }
    out
}
