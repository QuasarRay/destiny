"""Translate a complete new-Orbit case, including the original nested loops.

The finite AST grammar is reviewed against this exact fixture. Unknown syntax
fails before writing. Python reduction/power/libm, global settings, native
partition/Blue and production correspondence remain explicit boundaries.
"""
import argparse
import ast
import copy
import hashlib
import json
from pathlib import Path
from generate_park_harnesses import Translation,original,convert

ROOT=Path.cwd()
SOURCE="python/destiny/test/ballpark/evolve/test_orbit.py"
TARGET=ROOT/"verification/kani/src/orbit_contracts.rs"

PREAMBLE="""// Copyright © 2015 CCP ehf. MIT license, retained from original Destiny.
// Generated by generate_orbit_harnesses.py. Every original tick is retained.
// Bounds: two bodies, all four orbit ranges, 2000 ticks, 4096 ordered boundary
// calls. CPython 3.12.9 sum compensation and the original inclusive delta are
// retained; interpreter/libm/native/global-setting correspondence is required.
#![allow(non_snake_case)]
use destiny_original_spec::{OriginalParkProjection,OriginalBallInit,OriginalBallAttribute,
    OriginalGlobalSettings,Vec3,python_almost_equal_delta,python_sum_three_floats};
fn sum_squares(values:[f64;3]) -> f64 {
    python_sum_three_floats([values[0].powf(2.0),values[1].powf(2.0),values[2].powf(2.0)])
}
fn sum_products(left:[f64;3],right:[f64;3]) -> f64 {
    python_sum_three_floats([left[0]*right[0],left[1]*right[1],left[2]*right[2]])
}
"""

class NewOrbit(Translation):
    def __init__(self,source,body):
        super().__init__(source)
        self.evolve_method="evolve_two_spherical_bodies"
        assignments={}
        for n in ast.walk(body):
            if isinstance(n,ast.Assign) and len(n.targets)==1 and isinstance(n.targets[0],ast.Name):
                assignments.setdefault(n.targets[0].id,[]).append(n)
        self.mutable_names={name for name,nodes in assignments.items() if len(nodes)>1}
        self.initial_ints={name:node.value.value for name,nodes in assignments.items() for node in nodes[:1]
                           if isinstance(node.value,ast.Constant) and type(node.value.value)is int}
        self.declared=set()

    def expression(self,n):
        if isinstance(n,ast.Constant) and type(n.value)is int:return str(n.value)+"_i64","int"
        if isinstance(n,ast.BinOp) and isinstance(n.op,(ast.Add,ast.Sub,ast.Mult,ast.Div)):
            operator={ast.Add:"+",ast.Sub:"-",ast.Mult:"*",ast.Div:"/"}[type(n.op)]
            return "("+self.typed(n.left,"float")+" "+operator+" "+self.typed(n.right,"float")+")","float"
        if isinstance(n,ast.Compare) and len(n.ops)==1 and len(n.comparators)==1:
            operators={ast.Lt:"<",ast.Gt:">",ast.LtE:"<=",ast.GtE:">=",ast.Eq:"==",ast.NotEq:"!="}
            if type(n.ops[0]) not in operators:raise ValueError("Unreviewed comparison")
            left,lk=self.expression(n.left);right,rk=self.expression(n.comparators[0])
            if lk==rk=="int":return left+" "+operators[type(n.ops[0])]+" "+right,"bool"
            left=convert(left,lk,"float");right=convert(right,rk,"float")
            return "("+left+") "+operators[type(n.ops[0])]+" ("+right+")","bool"
        if isinstance(n,ast.List) and len(n.elts)==3:
            return "["+", ".join(self.typed(x,"float") for x in n.elts)+"]","float-array"
        if isinstance(n,ast.Call) and len(n.args)==1 and not n.keywords:
            method=ast.unparse(n.func)
            if method=="math.sqrt":return "("+self.typed(n.args[0],"float")+").sqrt()","float"
            if method=="abs":return "("+self.typed(n.args[0],"float")+").abs()","float"
            if method=="sum":
                comprehension=n.args[0]
                if not isinstance(comprehension,(ast.ListComp,ast.GeneratorExp)) or len(comprehension.generators)!=1:
                    raise ValueError("Unreviewed Python reduction")
                generator=comprehension.generators[0]
                if generator.ifs or generator.is_async or not isinstance(generator.target,ast.Name):
                    raise ValueError("Unreviewed comprehension")
                variable=generator.target.id
                if isinstance(comprehension.elt,ast.BinOp) and isinstance(comprehension.elt.op,ast.Pow):
                    if ast.unparse(comprehension.elt.left)!=variable or ast.literal_eval(comprehension.elt.right)!=2:
                        raise ValueError("Unreviewed power reduction")
                    code,kind=self.expression(generator.iter)
                    if kind!="float-array":raise ValueError("Three float values required")
                    return "sum_squares("+code+")","float"
                if isinstance(comprehension.elt,ast.BinOp) and isinstance(comprehension.elt.op,ast.Mult):
                    if ast.unparse(generator.iter)!="range(3)":raise ValueError("All three dot-product terms required")
                    arrays=[]
                    for access in (comprehension.elt.left,comprehension.elt.right):
                        if not isinstance(access,ast.Subscript) or ast.unparse(access.slice)!=variable:
                            raise ValueError("Unreviewed dot-product access")
                        code,kind=self.expression(access.value)
                        if kind!="float-array":raise ValueError("Dot product requires three floats")
                        arrays.append(code)
                    return "sum_products("+", ".join(arrays)+")","float"
                raise ValueError("Unreviewed reduction operator")
        return super().expression(n)

    def assignment(self,target,value):
        if isinstance(target,ast.Name) and target.id in self.mutable_names:
            code,kind=self.expression(value)
            if kind not in {"float","int"}:raise ValueError("Unreviewed mutable scalar")
            if target.id in self.declared:
                self.emit(target.id+"="+convert(code,kind,self.env[target.id])+";")
            else:
                self.env[target.id]=kind; self.declared.add(target.id)
                self.emit("let mut "+target.id+"="+code+";")
            return
        return super().assignment(target,value)

    def statement(self,n):
        if isinstance(n,ast.If):
            self.emit("if "+self.typed(n.test,"bool")+" {");self.indentation+=1
            for statement in n.body:self.statement(statement)
            self.indentation-=1;self.emit("}")
            if n.orelse:
                self.emit("else {");self.indentation+=1
                for statement in n.orelse:self.statement(statement)
                self.indentation-=1;self.emit("}")
            return
        if isinstance(n,ast.For) and isinstance(n.target,ast.Name) and not n.orelse:
            counter="original_counter_"+str(len(self.lines));stop="original_stop_"+str(len(self.lines))
            if isinstance(n.iter,ast.List):
                values=[ast.literal_eval(value) for value in n.iter.elts]
                if values!=[100.0,500.0,1000.0,2000.0]:raise ValueError("Original outer orbit ranges changed")
                self.emit("let "+stop+"=[100.0_f64,500.0_f64,1000.0_f64,2000.0_f64];")
                limit=stop+".len()";kind="float";counter_type="usize"
            elif isinstance(n.iter,ast.Call) and ast.unparse(n.iter.func)=="range" and len(n.iter.args)==1 and not n.iter.keywords:
                argument=n.iter.args[0]
                maximum=self.initial_ints.get(argument.id) if isinstance(argument,ast.Name) else ast.literal_eval(argument)
                if type(maximum)is not int or not 1<=maximum<=2000:raise ValueError("Unreviewed loop cardinality")
                self.maximum_iterations=max(self.maximum_iterations,maximum)
                self.emit("let "+stop+"="+self.typed(argument,"int")+"; // Python range evaluates its bound exactly once")
                limit=stop;kind="int";counter_type="i64"
            else:raise ValueError("Unreviewed original iteration")
            self.env[n.target.id]=kind
            self.emit(f"let mut {counter}=0_{counter_type};");self.emit(f"while {counter}<{limit} {{");self.indentation+=1
            self.emit("let "+n.target.id+"="+(stop+"["+counter+"]" if kind=="float" else counter)+";")
            self.emit("let _="+n.target.id+"; // retain the source loop binding even when only a comprehension shadows it")
            for statement in n.body:self.statement(statement)
            self.emit(counter+"+=1;");self.indentation-=1;self.emit("}");return
        if isinstance(n,ast.Expr) and isinstance(n.value,ast.Call) and ast.unparse(n.value.func)=="self.assertAlmostEqual":
            call=n.value
            if len(call.args)!=2 or len(call.keywords)!=1 or call.keywords[0].arg!="delta":
                raise ValueError("Original delta assertion required")
            self.emit(f"// original-assertion: {SOURCE}:{call.lineno}")
            self.emit("assert!(python_almost_equal_delta("+", ".join(self.typed(x,"float") for x in [*call.args,call.keywords[0].value])+"));")
            return
        return super().statement(n)

def translate(case):
    source,fixture,test=case.split("::")
    if source!=SOURCE or fixture!="TestNewOrbit":raise ValueError("Unreviewed source fixture")
    focus=json.loads((ROOT/".aegis/destiny/harness-focus.json").read_text())
    if focus["status"]!="OPEN" or focus["request"]["case"]!=case:raise ValueError("Corresponding OPEN work packet required")
    text=original(source);cls=next(n for n in ast.parse(text).body if isinstance(n,ast.ClassDef) and n.name==fixture)
    expected=ast.parse("class TestNewOrbit(helpers.BallparkTestCase):\n def setUp(self):\n  enable_new_orbit()\n  super(TestNewOrbit,self).setUp()\n  helpers.create_space_ball.next_object_id=1\n  self.orbitee=helpers.create_space_ball(self.park,x=0.0,y=0.0,z=0.0)\n  self.orbiter=helpers.create_space_ball(self.park,x=10.0)\n def tearDown(self):\n  reset_settings_to_default()\n  super(TestNewOrbit,self).tearDown()\n  del self.orbitee\n  del self.orbiter\n").body[0]
    actual=[n for n in cls.body if isinstance(n,ast.FunctionDef) and n.name in ("setUp","tearDown")]
    if [ast.dump(n) for n in actual]!=[ast.dump(n) for n in expected.body]:raise ValueError("Fixture lifecycle changed")
    class BindFixtureNames(ast.NodeTransformer):
        def visit_Attribute(self,node):
            if isinstance(node.value,ast.Name) and node.value.id=="self" and node.attr in ("orbiter","orbitee"):
                return ast.copy_location(ast.Name(id=node.attr,ctx=node.ctx),node)
            return self.generic_visit(node)
    method=next(n for n in cls.body if isinstance(n,ast.FunctionDef) and n.name==test)
    if method.decorator_list:raise ValueError("Unreviewed decorator")
    body=BindFixtureNames().visit(copy.deepcopy(method));translation=NewOrbit(source,body)
    translation.env["next_space_object_id"]="int"
    translation.emit("let mut next_space_object_id=1_i64; // original fixture resets the helper global counter")
    for statement in actual[0].body[3:]:translation.statement(BindFixtureNames().visit(copy.deepcopy(statement)))
    for statement in body.body:translation.statement(statement)
    proof=(f"\n// original-case: {case}\n// original-source-sha256: {hashlib.sha256(text.encode()).hexdigest()}\n"
           "#[cfg_attr(kani,kani::proof)]\n"+f"#[cfg_attr(kani,kani::unwind({max(28,translation.maximum_iterations+1)}))]\n"
           "#[cfg_attr(test,test)]\n"+f"fn {test}() {{\n"
           "    let mut settings=OriginalGlobalSettings::default();\n    let mut configured=settings.get();\n"
           "    configured.use_new_orbit=true;\n    settings.apply(configured);\n"
           "    let mut park=OriginalParkProjection::default();\n    park.use_new_orbit=settings.get().use_new_orbit;\n"
           +"\n".join(translation.lines)+"\n"
           "    let _final_helper_counter=next_space_object_id;\n"
           "    settings.reset();\n    park.use_new_orbit=settings.get().use_new_orbit;\n"
           "    park.clear_all();\n    assert!(!park.scope_error);\n    #[cfg(kani)]\n"
           "    kani::cover!(true,\"every original new Orbit iteration and assertion completed, including fixture teardown\");\n}\n")
    return proof

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--case",required=True);args=parser.parse_args()
    proof=translate(args.case);old=TARGET.read_text() if TARGET.exists() else PREAMBLE
    if "// original-case: "+args.case+"\n" in old:raise ValueError("Case already translated")
    TARGET.write_text(old+proof);print("Translated",args.case)

if __name__=="__main__":main()
