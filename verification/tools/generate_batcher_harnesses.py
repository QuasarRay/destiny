#!/usr/bin/env python3
"""Translate one reviewed ParkUpdateBatcher scenario from pinned Git ASTs.

Only reviewed history operations are accepted; native bubbles, streams and
network casts remain unimplemented until their complete dependencies are ported.
Run with the corresponding active Aegis packet. This generator creates no proof
credit and never replaces unsupported assertions with easier conditions.
"""
import argparse
import ast
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REV = "ef738406b61ad06bae2f402857e464735ab106a2"
SOURCE = "python/destiny/test/net/server/test_updatebatcher.py"
FIXTURE = "TestUpdateBatcher"
TARGET = ROOT / "verification/kani/src/update_batcher_contracts.rs"

PREAMBLE = """// Copyright © 2023 CCP ehf. MIT license, retained from original tests.
// Generated by verification/tools/generate_batcher_harnesses.py.
// Four keys/eight events per history and 32 unconnected signal emissions.
// Native park allocation/destruction, Python/weakref dispatch and representation
// correspondence remain required; no production refinement is claimed.
#![allow(non_snake_case)]
use destiny_original_spec::{ActionName, ActionValue, BatcherEvent, BatcherHistory,
    BatcherPayload, BoundedList, OriginalParkProjection, OriginalUpdateBatcher};
const CHAR_ID_1: i64 = 90000128;
const BUBBLE_1: i64 = 21;
fn goto_action() -> BatcherEvent {
    let mut args = BoundedList::new();
    assert!(args.push(ActionValue::Integer(1001)));
    assert!(args.push(ActionValue::Float(1.0)));
    assert!(args.push(ActionValue::Float(2.0)));
    assert!(args.push(ActionValue::Float(3.0)));
    BatcherEvent { timestamp: 0, name: ActionName::GotoPoint, payload: BatcherPayload::Tuple(args) }
}
fn stop_action() -> BatcherEvent {
    // Original STOP_ACTION is (0, ("Stop", (BALL_ID_1))), with scalar payload.
    BatcherEvent { timestamp: 0, name: ActionName::Stop, payload: BatcherPayload::Scalar(ActionValue::Integer(1001)) }
}
fn event_list(events: &[BatcherEvent]) -> BatcherHistory {
    let mut list = BatcherHistory::new();
    let mut i = 0_usize;
    while i < events.len() {
        if let Some(event) = events.get(i) { assert!(list.push(*event)); }
        i = i.saturating_add(1);
    }
    list
}
"""

def original():
    return subprocess.run(["git","show",f"{REV}:{SOURCE}"],cwd=ROOT,
        capture_output=True,text=True,check=True).stdout

def expression(n):
    if isinstance(n, ast.Name) and n.id in {"CHAR_ID_1","BUBBLE_1"}:
        return n.id, "id"
    if isinstance(n, ast.Name) and n.id in {"GOTO_ACTION","STOP_ACTION"}:
        return {"GOTO_ACTION":"goto_action()","STOP_ACTION":"stop_action()"}[n.id], "event"
    if isinstance(n, ast.List):
        values = [typed(x,"event") for x in n.elts]
        return "event_list(&[" + ", ".join(values) + "])", "history"
    if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and ast.unparse(n.func.value) == "self._update_batcher":
        method = n.func.attr
        if method not in {"get_character_history","get_bubble_history","character_has_history","bubble_has_history"} or len(n.args)!=1 or n.keywords:
            raise ValueError("Unimplemented batcher getter: " + ast.unparse(n))
        return f"batcher.{method}({typed(n.args[0],'id')})", "history" if method.startswith("get_") else "bool"
    raise ValueError("Unreviewed batcher expression: " + ast.unparse(n))

def typed(n,expected):
    code,kind = expression(n)
    if kind!=expected: raise ValueError(f"Unreviewed conversion {kind} -> {expected}")
    return code

def translate(case):
    source,fixture,test = case.split("::")
    if source!=SOURCE or fixture!=FIXTURE: raise ValueError("Unreviewed batcher fixture")
    text=original(); tree=ast.parse(text)
    constants={n.targets[0].id:n.value for n in tree.body if isinstance(n,ast.Assign)}
    for name,value in {"CHAR_ID_1":90000128,"BALL_ID_1":1001,"BUBBLE_1":21}.items():
        if ast.literal_eval(constants[name])!=value: raise ValueError("Original constant changed")
    for name,form in {"GOTO_ACTION":"(0, ('GotoPoint', (BALL_ID_1,1.0,2.0,3.0)))",
                      "STOP_ACTION":"(0, ('Stop', (BALL_ID_1)))"}.items():
        if ast.dump(constants[name])!=ast.dump(ast.parse(form,mode="eval").body):
            raise ValueError("Original event shape changed")
    cls=next(n for n in tree.body if isinstance(n,ast.ClassDef) and n.name==fixture)
    if [ast.unparse(b) for b in cls.bases]!=["DestinyTestCase"]: raise ValueError("Original fixture chain changed")
    fn=next(n for n in cls.body if isinstance(n,ast.FunctionDef) and n.name==test)
    if fn.decorator_list: raise ValueError("Unreviewed decorators")
    lines=[]; assertions=0
    for n in fn.body:
        if not isinstance(n,ast.Expr) or not isinstance(n.value,ast.Call):
            raise ValueError("Unreviewed batcher statement: " + ast.unparse(n))
        c=n.value
        if isinstance(c.func,ast.Attribute) and ast.unparse(c.func.value)=="self":
            name=c.func.attr
            if name=="assertListEqual" and len(c.args)==2 and not c.keywords:
                line=f"assert!({typed(c.args[0],'history')} == {typed(c.args[1],'history')});"
            elif name in {"assertTrue","assertFalse"} and len(c.args)==1 and not c.keywords:
                line="assert!(" + ("!" if name=="assertFalse" else "") + typed(c.args[0],"bool") + ");"
            else: raise ValueError("Unimplemented original batcher assertion: " + name)
            lines += [f"// original-assertion: {SOURCE}:{c.lineno}",line]; assertions+=1
        elif isinstance(c.func,ast.Attribute) and ast.unparse(c.func.value)=="self._update_batcher":
            name=c.func.attr
            if name=="add_to_character_history" and len(c.args)==2:
                if len(c.keywords)>1 or any(k.arg!="in_front" or not isinstance(k.value,ast.Constant) or type(k.value.value)is not bool for k in c.keywords):
                    raise ValueError("Unreviewed insertion keyword")
                front=str(c.keywords[0].value.value).lower() if c.keywords else "false"
                lines.append(f"assert!(batcher.add_to_character_history({typed(c.args[0],'id')}, {typed(c.args[1],'event')}, {front}) == Ok(()));")
            elif name=="add_to_bubble_history" and len(c.args)==2 and not c.keywords:
                lines.append(f"assert!(batcher.add_to_bubble_history({typed(c.args[0],'id')}, {typed(c.args[1],'event')}) == Ok(()));")
            elif name=="clear_character_history" and len(c.args)==1 and not c.keywords:
                lines.append(f"batcher.clear_character_history({typed(c.args[0],'id')});")
            else: raise ValueError("Unimplemented original batcher operation: " + name)
        else: raise ValueError("Unreviewed call: " + ast.unparse(c))
    if not assertions: raise ValueError("No reviewed original assertions")
    proof=f"\n// original-case: {case}\n// original-source-sha256: {hashlib.sha256(text.encode()).hexdigest()}\n"
    proof+="#[cfg_attr(kani,kani::proof)]\n#[cfg_attr(kani,kani::unwind(17))]\n#[cfg_attr(test,test)]\n"
    proof+=f"fn {test}() {{\n    let mut park = OriginalParkProjection::default();\n    park.is_master = true;\n    let mut batcher = OriginalUpdateBatcher::default();\n"
    proof+="".join("    "+line+"\n" for line in lines)
    proof+="    drop(batcher);\n    park.clear_all();\n    assert!(!park.scope_error);\n    #[cfg(kani)]\n    kani::cover!(true, \"original batcher history assertions and teardown completed\");\n}\n"
    return proof

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument("--case",required=True);a=p.parse_args()
    proof=translate(a.case);previous=TARGET.read_text() if TARGET.exists() else PREAMBLE
    if "// original-case: "+a.case+"\n" in previous: raise ValueError("Case already translated")
    TARGET.write_text(previous+proof); print("Translated",a.case)

if __name__=="__main__": main()
