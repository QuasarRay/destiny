#!/usr/bin/env python3
"""Translate one reviewed, fixture-qualified client merge scenario at a time.

The accepted AST grammar is deliberately small and fail-closed. Operations and
expected lists are translated from the pinned source, not inferred from names.
Run after destinyctl harness --case ID; close that packet before the next case.
"""

import argparse
import ast
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = "ef738406b61ad06bae2f402857e464735ab106a2"
SOURCE = "python/destiny/test/net/client/test_mergestateintohistory.py"
FIXTURE = "TestMergeStateIntoHistory"
TARGET = ROOT / "verification/kani/src/client_history_contracts.rs"
PREAMBLE = """// Copyright © 2023 CCP ehf. MIT license, retained from the original tests.
// Generated by verification/tools/generate_client_history_harnesses.py.
// The four-event/four-batch model includes all eleven original scenarios, whose
// maxima are two events per batch and two batches. Python import/aliasing
// correspondence remains a separate obligation.

use destiny_original_spec::{
    ClientHistory, ClientHistoryAction, ClientHistoryBatch, ClientHistoryEvent,
    ClientHistoryState, merge_client_state_into_history,
};

const GOTO_DIRECTION: ClientHistoryAction = ClientHistoryAction::GotoDirection {
    id: 1_000_000_176_143,
    direction: [1.0, 0.0, 0.0],
};
const STOP: ClientHistoryAction = ClientHistoryAction::Stop { id: 1_000_000_176_143 };

fn state(events: &[(i64, ClientHistoryAction)]) -> ClientHistoryState {
    let mut result = ClientHistoryState::new();
    let mut i: usize = 0;
    while i < events.len() {
        if let Some((timestamp, action)) = events.get(i) {
            assert!(result.push(ClientHistoryEvent { timestamp: *timestamp, action: *action }));
        }
        i = i.saturating_add(1);
    }
    result
}

fn concatenate(mut left: ClientHistoryState, right: ClientHistoryState) -> ClientHistoryState {
    assert!(left.extend(&right));
    left
}

fn history(batches: &[(ClientHistoryState, bool)]) -> ClientHistory {
    let mut result = ClientHistory::new();
    let mut i: usize = 0;
    while i < batches.len() {
        if let Some((state, wait_for_bubble)) = batches.get(i) {
            assert!(result.push(ClientHistoryBatch { state: *state, wait_for_bubble: *wait_for_bubble }));
        }
        i = i.saturating_add(1);
    }
    result
}

"""


def expression(node):
    if isinstance(node, ast.Name) and node.id != "self":
        return node.id
    if isinstance(node, ast.Constant) and isinstance(node.value, bool):
        return str(node.value).lower()
    if isinstance(node, ast.Constant) and type(node.value) is int:
        return str(node.value)
    if isinstance(node, ast.Tuple) and len(node.elts) == 2:
        return "(" + ", ".join(expression(x) for x in node.elts) + ")"
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return f"concatenate({expression(node.left)}, {expression(node.right)})"
    if isinstance(node, ast.List):
        if all(isinstance(x, ast.Tuple) for x in node.elts):
            return "state(&[" + ", ".join(expression(x) for x in node.elts) + "])"
        if all(isinstance(x, ast.List) and len(x.elts) == 2 for x in node.elts):
            batches = ["(" + ", ".join(expression(y) for y in x.elts) + ")" for x in node.elts]
            return "history(&[" + ", ".join(batches) + "])"
    raise ValueError(f"Unreviewed expression: {ast.dump(node)}")


def translate(case, original):
    prefix = f"{SOURCE}::{FIXTURE}::"
    if not case.startswith(prefix):
        raise ValueError("This generator accepts only the reviewed client merge fixture")
    test = case[len(prefix):]
    tree = ast.parse(original)
    cls = next(x for x in tree.body if isinstance(x, ast.ClassDef) and x.name == FIXTURE)
    method = next(x for x in cls.body if isinstance(x, ast.FunctionDef) and x.name == test)
    # Bind the constants' values and shapes rather than accepting arbitrary names.
    constants = {x.targets[0].id: x.value for x in tree.body if isinstance(x, ast.Assign)}
    assert ast.literal_eval(constants["SHIP_ID_1"]) == 1_000_000_176_143
    assert ast.dump(constants["GOTO_DIRECTION"]) == ast.dump(ast.parse("('GotoDirection', (SHIP_ID_1, 1.0, 0.0, 0.0))", mode="eval").body)
    assert ast.dump(constants["STOP"]) == ast.dump(ast.parse("('Stop', (SHIP_ID_1,))", mode="eval").body)
    statements = []
    assertions = 0
    for node in method.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name == "history_list" and isinstance(node.value, ast.List) and not node.value.elts:
                statements.append("let mut history_list = ClientHistory::new();")
            elif name.startswith("state") and isinstance(node.value, ast.List):
                statements.append(f"let {name} = {expression(node.value)};")
            else:
                raise ValueError(f"Unreviewed assignment at {node.lineno}")
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            call = node.value
            if isinstance(call.func, ast.Name) and call.func.id == "merge_state_into_history" and len(call.args) == 3 and not call.keywords:
                if not isinstance(call.args[1], ast.Name) or call.args[1].id != "history_list":
                    raise ValueError("Unexpected history destination")
                statements.append(f"assert!(merge_client_state_into_history(&{expression(call.args[0])}, &mut history_list, {expression(call.args[2])}) == Ok(()));")
            elif isinstance(call.func, ast.Attribute) and isinstance(call.func.value, ast.Name) and call.func.value.id == "self" and call.func.attr == "assertListEqual" and len(call.args) == 2 and not call.keywords:
                expected = call.args[0]
                if not isinstance(call.args[1], ast.Name) or call.args[1].id != "history_list":
                    raise ValueError("Unexpected comparison destination")
                expected_rust = "ClientHistory::new()" if isinstance(expected, ast.List) and not expected.elts else expression(expected)
                statements.append(f"// original-assertion: {SOURCE}:{node.lineno}")
                statements.append(f"assert!({expected_rust} == history_list);")
                assertions += 1
            else:
                raise ValueError(f"Unreviewed call at {node.lineno}: {ast.dump(call)}")
        else:
            raise ValueError(f"Unreviewed statement at {node.lineno}")
    if assertions != 1:
        raise ValueError("Each reviewed original scenario has exactly one complete list assertion")
    digest = hashlib.sha256(original.encode()).hexdigest()
    function = test.removeprefix("test_")
    return f"// original-case: {case}\n// original-source-sha256: {digest}\n#[cfg_attr(kani, kani::proof)]\n#[cfg_attr(kani, kani::unwind(9))]\n#[cfg_attr(test, test)]\nfn {function}() {{\n" + "\n".join("    " + line for line in statements) + "\n    #[cfg(kani)]\n    kani::cover!(true, \"complete original client history scenario\");\n}\n\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", required=True)
    args = parser.parse_args()
    original = subprocess.run(["git", "show", f"{REVISION}:{SOURCE}"], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    body = translate(args.case, original)
    existing = TARGET.read_text() if TARGET.exists() else PREAMBLE
    if f"// original-case: {args.case}\n" in existing:
        raise ValueError("Case is already translated; do not silently replace a reviewed harness")
    TARGET.write_text(existing + body)
    print(f"Translated {args.case}")


if __name__ == "__main__":
    main()
