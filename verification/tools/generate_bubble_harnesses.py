"""Translate one reviewed BubbleUpdater scenario from the pinned original AST.

Unknown syntax or an unimplemented Evolve dependency fails before writing a
counterpart. Native loading, allocation/destruction, Python sets and dispatch
remain separately required. Run only for the corresponding OPEN work packet.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import subprocess

ROOT=Path.cwd()
REV="ef738406b61ad06bae2f402857e464735ab106a2"
SOURCE="python/destiny/test/net/server/test_bubbleupdater.py"
TARGET=ROOT/"verification/kani/src/bubble_updater_contracts.rs"

def original(path):
    return subprocess.run(["git","show",REV+":"+path],cwd=ROOT,check=True,capture_output=True,text=True).stdout

PREAMBLE="""// Copyright © 2023 CCP ehf. MIT license, retained from original Destiny.
// Generated by generate_bubble_harnesses.py from the behavioral Git revision.
// Eight live balls, sixteen bubble entries, sixty-four top cells. Python set
// iteration, Blue construction/lifetime and native spatial correspondence
// remain required. These are specification counterparts, not refinement proofs.
use destiny_original_spec::{BoundedList,OriginalBallInit,OriginalParkProjection,
    OriginalBubbleUpdater,OriginalBubbleDelta as D,OriginalBubbleDeltaMap,
    OriginalBubbleEntry,Vec3};
fn ids(values:&[i64]) -> BoundedList<i64,8> {
    let mut result=BoundedList::new(); let mut i=0;
    while i<values.len() { if let Some(value)=values.get(i) { assert!(result.push(*value)); } i+=1; }
    result
}
fn deltas(values:&[(i64,D)]) -> OriginalBubbleDeltaMap {
    let mut result=BoundedList::new(); let mut i=0;
    while i<values.len() { if let Some(value)=values.get(i) { assert!(result.push(*value)); } i+=1; }
    result
}
fn maps_equal(left:&OriginalBubbleDeltaMap,right:&OriginalBubbleDeltaMap) -> bool {
    if left.len()!=right.len() { return false; }
    let mut i=0;
    while i<left.len() {
        let Some((key,value))=left.get(i) else { return false; };
        let mut matches=0; let mut j=0;
        while j<right.len() {
            if right.get(j)==Some((key,value)) { matches+=1; } j+=1;
        }
        if matches!=1 { return false; } i+=1;
    }
    true
}
fn entries(values:&[(i64,i64,i8)]) -> BoundedList<OriginalBubbleEntry,16> {
    let mut result=BoundedList::new(); let mut i=0;
    while i<values.len() {
        if let Some((bubble,ball,action))=values.get(i) {
            assert!(result.push(OriginalBubbleEntry { bubble:*bubble,ball:*ball,action:*action }));
        }
        i+=1;
    }
    result
}
fn dictionaries_equal(left:&BoundedList<OriginalBubbleEntry,16>,right:&BoundedList<OriginalBubbleEntry,16>) -> bool {
    if left.len()!=right.len() { return false; }
    let mut i=0;
    while i<left.len() {
        let value=left.get(i); let mut matches=0; let mut j=0;
        while j<right.len() { if value==right.get(j) { matches+=1; } j+=1; }
        if matches!=1 { return false; } i+=1;
    }
    true
}
"""

class Translate:
    def __init__(self,text):
        self.constants={n.targets[0].id:ast.literal_eval(n.value) for n in ast.parse(text).body
                        if isinstance(n,ast.Assign) and len(n.targets)==1 and isinstance(n.targets[0],ast.Name)}
        helper=next(n for n in ast.parse(original("python/destiny/test/net/server/helpers.py")).body
                    if isinstance(n,ast.FunctionDef) and n.name=="add_ball_to_park")
        args=[n.arg for n in helper.args.args]
        self.defaults=dict(zip(args[-len(helper.args.defaults):],helper.args.defaults))
        self.lines=[]; self.indent=1; self.created=0
    def emit(self,line):self.lines.append("    "*self.indent+line)
    def number(self,n):
        value=self.constants[n.id] if isinstance(n,ast.Name) and n.id in self.constants else ast.literal_eval(n)
        if type(value) not in (int,float): raise ValueError("Unreviewed numeric representation")
        return value
    def integer(self,n):
        value=self.number(n)
        if type(value)is not int or not -(1<<63)<=value<(1<<63): raise ValueError("Original int64 scope")
        return str(value)+"_i64"
    def expected(self,n):
        if not isinstance(n,ast.Dict):raise ValueError("Original dictionary comparison required")
        if any(isinstance(value,ast.Dict) for value in n.values):
            values=[]
            for key,inner in zip(n.keys,n.values):
                if not isinstance(inner,ast.Dict):raise ValueError("Unreviewed mixed dictionary")
                for ball,action in zip(inner.keys,inner.values):
                    action_value=self.number(action)
                    if action_value not in (-1,0,1):raise ValueError("Unreviewed bubble action")
                    values.append(f"({self.integer(key)},{self.integer(ball)},{action_value}_i8)")
            return "entries(&["+", ".join(values)+"])","entries"
        values=[]
        for key,value in zip(n.keys,n.values):
            if isinstance(value,ast.List): payload="D::Balls(ids(&["+", ".join(self.integer(x) for x in value.elts)+"]))"
            else:payload="D::Bubble("+self.integer(value)+")"
            values.append("("+self.integer(key)+","+payload+")")
        return "deltas(&["+", ".join(values)+"])","deltas"
    def creation(self,call):
        if len(call.args)!=1 or ast.unparse(call.args[0])!="self._park":raise ValueError("Unreviewed original park")
        values=dict(self.defaults)
        for key in call.keywords:
            if key.arg not in values:raise ValueError("Unreviewed helper argument")
            values[key.arg]=key.value
        if len({key.arg for key in call.keywords})!=len(call.keywords):raise ValueError("Repeated helper argument")
        fields=[]
        for argument,field,kind in [
            ("ball_id","id","int"),("mass","mass","f64"),("radius","radius","f32"),
            ("max_velocity","max_velocity","f32"),("agility","agility","f32"),
            ("speed_fraction","speed_fraction","f32"),("is_free","is_free","bool"),
            ("is_global","is_global","bool"),("is_massive","is_massive","bool"),
            ("is_interactive","is_interactive","bool"),("is_space_junk","is_space_junk","bool")]:
            if kind=="int":code=self.integer(values[argument])
            elif kind=="bool":
                value=ast.literal_eval(values[argument])
                if type(value)is not bool:raise ValueError("Unreviewed fixture truth conversion")
                code=str(value).lower()
            else:code=repr(float(self.number(values[argument])))+"_"+kind
            fields.append(field+":"+code)
        for vector,arguments in [("position",("x","y","z")),("velocity",("vx","vy","vz"))]:
            fields.append(vector+":Vec3 { "+", ".join(axis+":"+repr(float(self.number(values[arg])))+"_f64" for axis,arg in zip("xyz",arguments))+" }")
        self.emit("assert!(!park.dynamical_orientation); // settings selects the original 18-argument constructor")
        self.emit("let created_ball_"+str(self.created)+"=park.add_ball(OriginalBallInit { "+", ".join(fields)+" });")
        self.emit(f"assert!(park.contains(created_ball_{self.created}) && !park.scope_error);")
        self.emit(f"assert!(park.insert_new_query_ball(created_ball_{self.created})==Ok(()));")
        self.created+=1
    def statement(self,n):
        if isinstance(n,ast.For) and isinstance(n.target,ast.Name) and n.target.id=="_" and not n.orelse:
            if ast.unparse(n.iter)!="range(3)":raise ValueError("Unreviewed loop domain")
            self.emit("let mut original_iteration=0;");self.emit("while original_iteration<3 {");self.indent+=1
            for statement in n.body:self.statement(statement)
            self.emit("original_iteration+=1;");self.indent-=1;self.emit("}");return
        if not isinstance(n,ast.Expr) or not isinstance(n.value,ast.Call):raise ValueError("Unreviewed original statement")
        call=n.value; method=ast.unparse(call.func)
        if method=="add_ball_to_park":self.creation(call);return
        if method=="self._bubble_updater.additions_and_deletions" and not call.args and not call.keywords:
            self.emit("assert!(updater.additions_and_deletions(&mut park)==Ok(()));");return
        if method=="self._park.Evolve" and not call.args and not call.keywords:
            self.emit("assert!(park.evolve_two_spherical_bodies()==Ok(()));");return
        if method=="self._park.RemoveBall" and len(call.args)==1 and not call.keywords:
            self.emit("park.remove_ball("+self.integer(call.args[0])+",0);");return
        if method=="self.assertEqual" and len(call.args)==2 and not call.keywords:
            expected,kind=self.expected(call.args[0]);target=ast.unparse(call.args[1])
            fields=("additions_per_player","deletions_per_player","additions_per_bubble","deletions_per_bubble")
            self.emit(f"// original-assertion: {SOURCE}:{call.lineno}")
            if target in {"self._bubble_updater."+field for field in fields} and kind=="deltas":
                field=target.rsplit(".",1)[1];self.emit(f"assert!(maps_equal(&{expected},&updater.updates.{field}));");return
            if target=="self._park.bubbles" and kind=="entries":
                self.emit(f"assert!(dictionaries_equal(&{expected},&park.bubble_dictionary_entries()));");return
        raise ValueError("Unimplemented original operation: "+ast.unparse(call))

def translate(case):
    source,fixture,test=case.split("::")
    if source!=SOURCE or fixture!="TestBubbleUpdater":raise ValueError("Unreviewed fixture")
    focus=json.loads((ROOT/".aegis/destiny/harness-focus.json").read_text())
    if focus["status"]!="OPEN" or focus["request"]["case"]!=case:raise ValueError("Corresponding OPEN work packet required")
    text=original(source);cls=next(n for n in ast.parse(text).body if isinstance(n,ast.ClassDef) and n.name==fixture)
    expected=ast.parse("class TestBubbleUpdater(unittest.TestCase):\n def setUp(self):\n  self._park=destiny.Ballpark()\n  self._park.isMaster=True\n  self._bubble_updater=BubbleUpdater(self._park)\n def tearDown(self):\n  del self._park\n  del self._bubble_updater\n").body[0]
    actual=[n for n in cls.body if isinstance(n,ast.FunctionDef) and n.name in ("setUp","tearDown")]
    if [ast.dump(n) for n in actual]!=[ast.dump(n) for n in expected.body]:raise ValueError("Fixture lifecycle changed")
    method=next(n for n in cls.body if isinstance(n,ast.FunctionDef) and n.name==test)
    if method.decorator_list:raise ValueError("Unreviewed decorator")
    translation=Translate(text)
    for n in method.body:translation.statement(n)
    return (f"\n// original-case: {case}\n// original-source-sha256: {hashlib.sha256(text.encode()).hexdigest()}\n"
            "#[cfg_attr(kani,kani::proof)]\n#[cfg_attr(kani,kani::unwind(65))]\n#[cfg_attr(test,test)]\n"
            f"fn {test}() {{\n    let mut park=OriginalParkProjection::default();\n    park.is_master=true;\n"
            "    {\n    let mut updater=OriginalBubbleUpdater::default();\n"+"\n".join(translation.lines)+"\n"
            "    } // updater and its park reference end before the native park destruction boundary\n"
            "    park.clear_all();\n    assert!(!park.scope_error);\n    #[cfg(kani)]\n"
            "    kani::cover!(true,\"all original bubble updater assertions and fixture teardown completed\");\n}\n")

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--case",required=True);args=parser.parse_args()
    proof=translate(args.case);old=TARGET.read_text() if TARGET.exists() else PREAMBLE
    if "// original-case: "+args.case+"\n" in old:raise ValueError("Case already translated")
    TARGET.write_text(old+proof);print("Translated",args.case)

if __name__=="__main__":main()
